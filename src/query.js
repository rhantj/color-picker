// 사용자 질의를 "비었는가" 판정하기 전에 정리한다.
//
// `.trim()` 은 유니코드 서식 문자(Cf — U+200B zero-width space, U+2060 word joiner 같은 것)를
// 공백으로 안 본다. 그런 문자만 있는 질의가 빈 질의 검사를 지나면 전문 검색은 아무것도 못 잡고,
// 구조 선택·재질 배정·질의 재작성이 **근거 없이 모델을 한 번씩 부른다**(17-A 가 기록한 갭).
// 세 곳이 같은 판단을 하므로 한 함수에 둔다 — 따로 두면 한 곳만 고쳐지는 일이 실제로 있었다.
//
// 지우는 것이지 거부하는 것이 아니다. 진짜 질의에 섞인 서식 문자는 그것만 빠지고 나머지는 그대로 간다.
//
// 트레이드오프: Cf 에는 이모지를 잇는 ZWJ(U+200D)도 들어간다. 가족·직업 이모지 같은 결합 시퀀스가 질의에
// 섞이면 낱개 이모지로 풀린다. 이 사이트의 검색은 한글·영숫자 어절만 토큰으로 삼아(`tokenize.js`) 이모지를
// 원래 버리므로 결과가 달라지지 않는다 — 그래서 ZWJ 를 예외로 두지 않는다.

const FORMAT_CHARS = /\p{Cf}/gu;

/** @param {unknown} query @returns {string} 서식 문자를 빼고 양끝 공백을 지운 문자열. 문자열이 아니면 "". */
export const cleanQuery = (query) => (typeof query === "string" ? query.replace(FORMAT_CHARS, "").trim() : "");
